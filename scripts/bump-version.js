#!/usr/bin/env node
"use strict";

/**
 * Increment the displayed app version by 0.01 (v1.80 → v1.81).
 * Run once before every GitHub push — never from npm start.
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const outPath = path.join(root, "version.js");

function readBuild() {
  try {
    const txt = fs.readFileSync(outPath, "utf8");
    const m = txt.match(/build:\s*(\d+)/);
    const n = m ? parseInt(m[1], 10) : 0;
    return Number.isFinite(n) && n > 0 ? n : 0;
  } catch {
    return 0;
  }
}

const build = readBuild() + 1;
const content = `// Auto-generated by scripts/bump-version.js (GitHub push)\nexport default { build: ${build} };\n`;
fs.writeFileSync(outPath, content);
console.log(`Bumped version to v1.${build}`);

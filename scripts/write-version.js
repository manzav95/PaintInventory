#!/usr/bin/env node
"use strict";

/**
 * Keep version.js valid for the client. Does not change the build number.
 * Version increases only via `node scripts/bump-version.js` on GitHub push.
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const outPath = path.join(root, "version.js");

let build = 1;
try {
  const txt = fs.readFileSync(outPath, "utf8");
  const m = txt.match(/build:\s*(\d+)/);
  const n = m ? parseInt(m[1], 10) : 0;
  if (Number.isFinite(n) && n > 0) build = n;
} catch {
  // missing file — write the default
}

const content = `// Auto-generated by scripts/bump-version.js (GitHub push)\nexport default { build: ${build} };\n`;
fs.writeFileSync(outPath, content);
console.log("Version written: v1." + build);
